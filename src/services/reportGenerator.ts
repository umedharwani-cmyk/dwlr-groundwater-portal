import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { DWLRStation, ReplenishmentActionPlan } from '../types';

export function exportStationReportPDF(station: DWLRStation, plan: ReplenishmentActionPlan) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 40, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('CENTRAL GROUND WATER BOARD / STATE GROUND WATER AUTHORITY', 14, 16);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(56, 189, 248); // sky-400
  doc.text(`Digital Water Level Recorder (DWLR) - Aquifer Assessment & Replenishment Plan`, 14, 25);

  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text(`State: ${station.state.toUpperCase()} | District: ${station.district} | Station Code: ${station.code}`, 14, 33);
  doc.text(`Report Date: ${new Date().toLocaleDateString()}`, pageWidth - 55, 33);

  // Station Metadata
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('1. Station Telemetry & Hydrogeological Profile', 14, 50);

  const profileData = [
    ['Station Name', station.name, 'Block / Village', `${station.block} / ${station.village}`],
    ['Aquifer Type', station.aquiferType, 'Altitude', `${station.altitudeM} m MSL`],
    ['Coordinates', `${station.lat.toFixed(4)}°N, ${station.lng.toFixed(4)}°E`, 'Installed Date', station.installedDate],
    ['Current Water Depth', `${station.currentDepthMgl.toFixed(2)} m bgl`, '10-Yr Baseline Depth', `${station.baselineDepthMgl.toFixed(2)} m bgl`],
    ['Annual Depletion Rate', `+${station.depthTrendPerYearM.toFixed(2)} m/year`, 'Stage of Extraction (SOE)', `${station.stageOfExtractionPct.toFixed(1)}%`],
    ['Current Water Salinity (TDS)', `${station.salinityTdsPpm} ppm`, 'Monsoon Rainfall Normal/Actual', `${station.annualRainfallNormalMm} / ${station.annualRainfallActualMm} mm`],
    ['Assigned Category', station.status.toUpperCase(), 'Urgency Priority Rank', `Priority ${station.urgencyPriorityRank} (UPS: ${station.urgencyPriorityScore}/100)`]
  ];

  autoTable(doc, {
    startY: 55,
    theme: 'grid',
    head: [],
    body: profileData,
    styles: { fontSize: 8.5, cellPadding: 3 },
    columnStyles: {
      0: { fontStyle: 'bold', fillColor: [241, 245, 249], cellWidth: 45 },
      1: { cellWidth: 50 },
      2: { fontStyle: 'bold', fillColor: [241, 245, 249], cellWidth: 45 },
      3: { cellWidth: 50 }
    }
  });

  // Urgency & Deficit Analysis
  const finalY1 = (doc as any).lastAutoTable.finalY || 120;

  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('2. Replenishment Action Plan & Engineered Interventions', 14, finalY1 + 10);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(
    `Annual Ground Water Deficit: ${plan.annualDeficitMcm} MCM | Projected Full Aquifer Recovery: ${plan.projectedRecoveryYears} Years`,
    14,
    finalY1 + 17
  );

  const tableRows = plan.recommendedInterventions.map((item, idx) => [
    (idx + 1).toString(),
    item.intervention.title,
    item.intervention.traditionalName || item.intervention.category.toUpperCase(),
    `${item.recommendedUnits} Units`,
    `${item.subtotalRechargeMcm} MCM/yr`,
    `Rs. ${item.subtotalCostLakhs} Lakhs`
  ]);

  autoTable(doc, {
    startY: finalY1 + 22,
    head: [['#', 'Intervention Title', 'Structure Type', 'Units', 'Recharge Capacity', 'Estimated Budget']],
    body: tableRows,
    theme: 'striped',
    headStyles: { fillColor: [2, 132, 199] },
    styles: { fontSize: 8 }
  });

  const finalY2 = (doc as any).lastAutoTable.finalY || 180;

  // Budget & Recovery Summary
  doc.setFillColor(240, 249, 255);
  doc.rect(14, finalY2 + 5, pageWidth - 28, 22, 'F');
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(3, 105, 161);
  doc.text(`Total Project Investment: Rs. ${plan.totalEstimatedCostLakhs} Lakhs`, 20, finalY2 + 13);
  doc.text(`Total Recharge Potential: ${plan.totalRechargePotentialMcm} MCM/yr (${plan.deficitOffsetPct}% Deficit Offset)`, 20, finalY2 + 21);

  // Policy Directives
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('3. Regulatory Directives & Demand Management Policies', 14, finalY2 + 35);

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  plan.policyMandates.forEach((mandate, idx) => {
    doc.text(`[${idx + 1}] ${mandate}`, 14, finalY2 + 43 + idx * 6);
  });

  // Footer / Authorization Stamp
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by HydroPulse Real-Time DWLR Monitoring System | CGWB & State Groundwater Departments', 14, pageHeight - 10);
  doc.text('Official Seal / Superintending Hydrogeologist', pageWidth - 80, pageHeight - 10);

  // Save PDF
  doc.save(`CGWB_DWLR_${station.code}_${station.district}_Plan.pdf`);
}

export function exportStationsCSV(stations: DWLRStation[]) {
  const headers = [
    'Station Code',
    'Station Name',
    'State',
    'District',
    'Block',
    'Village',
    'Latitude',
    'Longitude',
    'Aquifer Type',
    'Current Depth (mbgl)',
    '10-Yr Baseline (mbgl)',
    'Annual Trend (m/yr)',
    'Stage of Extraction (%)',
    'Salinity TDS (ppm)',
    'Severity Status',
    'Urgency Priority Score',
    'Priority Rank',
    'Dependent Population'
  ];

  const rows = stations.map((s) => [
    s.code,
    `"${s.name}"`,
    s.state,
    s.district,
    s.block,
    s.village,
    s.lat,
    s.lng,
    `"${s.aquiferType}"`,
    s.currentDepthMgl,
    s.baselineDepthMgl,
    s.depthTrendPerYearM,
    s.stageOfExtractionPct,
    s.salinityTdsPpm,
    s.status,
    s.urgencyPriorityScore,
    s.urgencyPriorityRank,
    s.populationDependent
  ]);

  const csvContent = 'data:text/csv;charset=utf-8,' + [headers.join(','), ...rows.map((e) => e.join(','))].join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', `DWLR_Groundwater_Evaluation_${new Date().toISOString().split('T')[0]}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
